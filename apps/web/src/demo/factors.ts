import type { EmissionFactor } from '@carbon-glint/sdk';

export interface DemoFactor extends EmissionFactor {
  key: string;
  /** Search keywords beyond name/category. */
  tags: string;
}

const SOURCE = {
  sourceCode: 'DEFRA_2026',
  sourceName: 'UK Government GHG Conversion Factors for Company Reporting 2026',
};
const CITATION = 'https://www.gov.uk/government/collections/government-conversion-factors-for-company-reporting';
const UNIT_LABEL: Record<string, string> = {
  kWh: 'kWh',
  L: 'litres',
  m3: 'cubic metres',
  kg: 'kg',
  t: 'tonnes',
  km: 'km',
  'passenger.km': 'passenger km',
  'tonne.km': 'tonne km',
  'room.night': 'room per night',
  unit: 'items',
};

let n = 0;
/** One library factor. `split` = share of CO2 / CH4 / N2O (combustion factors); omit for non-combustion. */
function f(
  key: string,
  name: string,
  category: string,
  unit: string,
  co2e: number,
  scopeHint: 1 | 2 | 3,
  region: string,
  tags = '',
  split: boolean = false,
): DemoFactor {
  n += 1;
  return {
    id: `demo-factor-${key}`,
    key,
    tags,
    ...SOURCE,
    externalId: `1_${100 + n}_${1000 + n * 7}_${n}`,
    name,
    category,
    scopeHint,
    region,
    year: 2026,
    unit,
    unitLabel: UNIT_LABEL[unit] ?? unit,
    co2ePerUnit: co2e,
    co2PerUnit: split ? Number((co2e * 0.9867).toFixed(5)) : null,
    ch4PerUnit: split ? Number((co2e * 0.0015).toFixed(5)) : null,
    n2oPerUnit: split ? Number((co2e * 0.0046).toFixed(5)) : null,
    citationUrl: CITATION,
  };
}


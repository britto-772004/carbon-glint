export const factorByKey = (key: string): DemoFactor => {
  const found = FACTORS.find((x) => x.key === key);
  if (!found) throw new Error(`Unknown demo factor ${key}`);
  return found;
};
export const factorById = (id: string): DemoFactor | undefined => FACTORS.find((x) => x.id === id);

/** Unit conversions the demo engine understands (activity unit → factor unit). */
const CONV: Record<string, Record<string, number>> = {
  kWh: { kWh: 1, MWh: 0.001, GWh: 1e-6 },
  MWh: { kWh: 1000, MWh: 1 },
  L: { L: 1, kL: 0.001, m3: 0.001 },
  kL: { L: 1000, kL: 1 },
  m3: { m3: 1, L: 1000 },
  kg: { kg: 1, t: 0.001 },
  t: { t: 1, kg: 1000 },
  km: { km: 1 },
  'passenger.km': { 'passenger.km': 1 },
  'tonne.km': { 'tonne.km': 1 },
  'room.night': { 'room.night': 1 },
  unit: { unit: 1 },
};
export const conversion = (from: string, to: string): number | null => CONV[from]?.[to] ?? null;
export const compatibleUnits = (from: string): string[] => Object.keys(CONV[from] ?? {});
